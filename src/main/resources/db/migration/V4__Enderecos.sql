-- Varios enderecos por usuario ("Casa", "Casa da mae", "Trabalho"), um deles principal.
CREATE TABLE enderecos (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   BIGINT       NOT NULL REFERENCES usuarios(id),
    apelido      VARCHAR(40)  NOT NULL,
    logradouro   VARCHAR(200) NOT NULL,
    complemento  VARCHAR(100),
    bairro       VARCHAR(80)  NOT NULL,
    cidade       VARCHAR(60)  NOT NULL DEFAULT 'Sao Paulo',
    uf           VARCHAR(2)   NOT NULL DEFAULT 'SP',
    principal    BOOLEAN      NOT NULL DEFAULT FALSE,
    criado_em    TIMESTAMP    NOT NULL
);
CREATE INDEX idx_enderecos_usuario ON enderecos(usuario_id);

