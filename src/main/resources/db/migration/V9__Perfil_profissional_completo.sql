-- Outros serviços que o prestador também faz (além da categoria principal); recebe os pedidos de todos
CREATE TABLE prestador_categorias (
    prestador_id  BIGINT NOT NULL REFERENCES prestadores(id) ON DELETE CASCADE,
    categoria_id  BIGINT NOT NULL REFERENCES categorias(id),
    PRIMARY KEY (prestador_id, categoria_id)
);

-- Galeria de trabalhos já realizados (até 6 fotos, data URI base64 enviada pelo app)
CREATE TABLE prestador_fotos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prestador_id  BIGINT       NOT NULL REFERENCES prestadores(id) ON DELETE CASCADE,
    imagem        TEXT         NOT NULL,
    legenda       VARCHAR(80),
    criada_em     TIMESTAMP    NOT NULL
);
CREATE INDEX idx_prestador_fotos ON prestador_fotos(prestador_id);

