CREATE TABLE usuarios (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(120) NOT NULL,
    email         VARCHAR(150) NOT NULL UNIQUE,
    senha         VARCHAR(100) NOT NULL,
    telefone      VARCHAR(20),
    bairro        VARCHAR(80)  NOT NULL,
    papel         VARCHAR(20)  NOT NULL,
    criado_em     TIMESTAMP    NOT NULL
);

CREATE TABLE categorias (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(60)   NOT NULL UNIQUE,
    descricao      VARCHAR(500)  NOT NULL,
    preco_minimo   NUMERIC(10,2) NOT NULL,
    preco_maximo   NUMERIC(10,2) NOT NULL
);

CREATE TABLE prestadores (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       BIGINT       NOT NULL UNIQUE REFERENCES usuarios(id),
    categoria_id     BIGINT       NOT NULL REFERENCES categorias(id),
    descricao        VARCHAR(500),
    nota_media       NUMERIC(3,2) NOT NULL DEFAULT 0,
    total_avaliacoes INT          NOT NULL DEFAULT 0
);

CREATE TABLE solicitacoes (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id           BIGINT        NOT NULL REFERENCES usuarios(id),
    categoria_id         BIGINT        NOT NULL REFERENCES categorias(id),
    prestador_id         BIGINT        REFERENCES prestadores(id),
    descricao            VARCHAR(1000) NOT NULL,
    bairro               VARCHAR(80)   NOT NULL,
    urgencia             VARCHAR(10)   NOT NULL,
    preco_minimo         NUMERIC(10,2) NOT NULL,
    preco_maximo         NUMERIC(10,2) NOT NULL,
    resumo_triagem       VARCHAR(500),
    dica_seguranca       VARCHAR(500),
    origem_triagem       VARCHAR(10)   NOT NULL,
    status               VARCHAR(20)   NOT NULL,
    criada_em            TIMESTAMP     NOT NULL,
    atualizada_em        TIMESTAMP     NOT NULL
);

CREATE TABLE avaliacoes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id  BIGINT       NOT NULL UNIQUE REFERENCES solicitacoes(id),
    prestador_id    BIGINT       NOT NULL REFERENCES prestadores(id),
    nota            INT          NOT NULL,
    comentario      VARCHAR(500),
    criada_em       TIMESTAMP    NOT NULL
);

CREATE TABLE notificacoes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      BIGINT       NOT NULL REFERENCES usuarios(id),
    solicitacao_id  BIGINT       NOT NULL REFERENCES solicitacoes(id),
    mensagem        VARCHAR(300) NOT NULL,
    lida            BOOLEAN      NOT NULL DEFAULT FALSE,
    criada_em       TIMESTAMP    NOT NULL
);

CREATE INDEX idx_solicitacoes_status_categoria ON solicitacoes(status, categoria_id);
CREATE INDEX idx_notificacoes_usuario ON notificacoes(usuario_id, lida);
