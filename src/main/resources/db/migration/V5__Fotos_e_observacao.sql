-- Ate 3 fotos do problema por pedido (imagem JPEG/PNG em base64, enviada pelo app)
CREATE TABLE solicitacao_fotos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id  BIGINT    NOT NULL REFERENCES solicitacoes(id) ON DELETE CASCADE,
    ordem           INT       NOT NULL,
    imagem          TEXT      NOT NULL,
    criada_em       TIMESTAMP NOT NULL
);
CREATE INDEX idx_fotos_solicitacao ON solicitacao_fotos(solicitacao_id);
